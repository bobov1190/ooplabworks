public class Contact {

    private String first, last, number;

    public Contact(String first, String last, String number) {
        this.first = first;
        this.last = last;
        this.number = number;
    }

    public String getFirst() {
        return first;
    }

    public String getLast() {
        return last;
    }

    public String getNumber() {
        return number;
    }
}
